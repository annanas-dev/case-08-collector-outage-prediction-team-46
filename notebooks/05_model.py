def boot_pair(frame, t, a, b, n_boot=1000):
    """PR-AUC оценок a и b и их разность с 95 % интервалами бутстрепа по блокам 28 суток и по объектам. Один seed –
    одни и те же повторные выборки для всех трех величин, поэтому разность парная. «шире» – интервал, который
    публикуем."""
    y = f"цель_{t}"
    f = frame[["день", "ид_объект", y, a, b]]
    fns = {"модель": lambda g: md.average_precision(g[y], g[a]),
           "частотный": lambda g: md.average_precision(g[y], g[b]),
           "разность": lambda g: md.average_precision(g[y], g[a]) - md.average_precision(g[y], g[b])}
    out = {}
    for name, fn in fns.items():
        blk = md.block_bootstrap(f, fn, block_days=28, n=n_boot, seed=7)
        obj = md.cluster_bootstrap(f, fn, n=n_boot, seed=7)
        wide = ("блоки", blk) if blk[2] - blk[1] >= obj[2] - obj[1] else ("объекты", obj)
        out[name] = {"блоки": blk, "объекты": obj, "шире": wide[1], "шире_по": wide[0]}
    return out


def ci(v):
    return f"{v[0]:.3f} [{v[1]:.3f}; {v[2]:.3f}]"


def ci_table(boots):
    rows = []
    for t, b in boots.items():
        rows.append({"цель": t, **{f"pr_auc_{k}": ci(b[k]["шире"]) for k in ["модель", "частотный"]},
                     "разность_модель_минус_частотный": ci(b["разность"]["шире"]),
                     "разность_блоки_28_суток": ci(b["разность"]["блоки"]),
                     "разность_объекты": ci(b["разность"]["объекты"]),
                     "шире_по": b["разность"]["шире_по"], "разность_выше_нуля": b["разность"]["шире"][1] > 0})
    return pd.DataFrame(rows).set_index("цель")


