# ## 2. Схема проверки
#
# | Шаг | Данные | Зачем |
# |---|---|---|
# | Подбор параметров | обучение, скользящие фолды: учим на 2019-2021 → проверяем 2022; на 2019-2022 → 2023; на 2019-2023 → 2024 | параметры выбираются без взгляда на 2025-2026; три года – проверка, что выигрыш не случайность одного года |
# | Число деревьев | медиана лучших итераций выбранного набора по фолдам и сидам | финальная модель учится без ранней остановки на валидации, чтобы валидация осталась честной |
# | Финальная модель | все обучение 2019-2024 без масок, 5 сидов | максимум истории |
# | Калибровка | для решений на валидации – перекрестно по половинам 2025 года; для теста и сервиса – Platt на последних 12 месяцах до периода (весь 2025 год) | вероятности приводим к свежей доле инцидентов |
# | Пороги уровней | подбор на 2024 годе (прогноз модели, обученной до 2023), проверка на 2025; для теста и сервиса та же процедура сдвигается на год | обещание нагрузки и точности проверено вне выборки |
# | Оценка | тест 2026 – один раз, в конце | итоговая цифра для заказчика |
#
# Почему именно так. Время в данных течет в одну сторону: доля инцидентов растет, в 2025 году сменилась разметка флага.
# Случайное перемешивание строк дало бы модели соседние сутки того же объекта в обучении и проверке и завысило бы
# качество. Скользящие фолды имитируют реальную работу: учимся на прошлом, прогнозируем следующий год.
#
# **Статус теста.** Скажем прямо: период январь-июнь 2026 года уже просматривался предыдущими версиями этой
# цепочки – с другим определением выборки (тихие сутки объекта тогда выбрасывались, «Много неисправных устройств»
# входило в отказ) и без маски плановых работ АКМ. Общее впечатление о тесте у команды поэтому есть, и совсем
# нетронутым его назвать нельзя. Защита от подгонки под тест здесь процедурная: параметры, число деревьев,
# калибровка, пороги и сила сглаживания частот в этом ноутбуке выбираются только по фолдам 2022-2024 и валидации
# 2025 по правилам, записанным до расчета, а тест применяется в разделе 11 один раз, после записи всех решений.
# Ни одно решение ниже не пересматривалось по результату теста.
#
# Почему маски не участвуют. Замаскированные сутки – это переход СМВУ, сбои, сутки до подключения объекта, сутки
# после суток молчания постоянно пишущего объекта и окна ППР АКМ: метка «0» в них значит «не знаем», а массовые
# артефактные тревоги перехода и проверок тестовым газом выглядели бы как «инциденты». Ни учить, ни оценивать на них
# нельзя. Для сервиса правило то же: сутки окна ППР по графику помечаются маской «плановые работы АКМ», и
# диспетчер видит, что на объекте идут плановые работы, а не повышенный риск.
#
# ## 3. Первая модель на скользящих фолдах и шум сида
#
# **Гипотеза.** Модель должна обойти частотный прогноз: кроме истории самой цели она видит дребезг датчиков, открытые
# на полночь тревоги, часы с последнего эпизода, потерю связи, телеметрию газа и температуры, насосы, соседние
# объекты, календарь (включая производственный: праздники и переносы) и постоянные свойства объекта.
#
# **Проверка.** LightGBM с умеренными параметрами без подбора: 31 лист, шаг 0,05, не меньше 100 строк в листе, 80 %
# признаков и строк на дерево, 500 деревьев. Модель случайна: какие строки и признаки попадут в каждое дерево,
# решает сид генератора. Поэтому на каждом фолде учим три копии с сидами 0, 1, 2 и смотрим три вещи: PR-AUC каждой
# копии (разброс между ними – **шум сида**, то есть сколько PR-AUC меняется от одной только случайности обучения),
# PR-AUC среднего прогноза трех копий и PR-AUC частотного прогноза на проверочном годе.

