# ## 9. Газ, потеря связи и неисправность охраны: сглаженная частота
#
# **Постановка.** Для газа, потери связи и неисправности охраны («Состояние охраны: Много неисправных устройств»)
# модель не строим. У газа и потери связи во всей валидации 17 и 23 положительных суток на 78 объектов, в тесте 15 и
# 33; на таком числе примеров нельзя ни подобрать параметры, ни проверить калибровку. У газа после маски ППР АКМ
# осталось только 26-42 % положительных суток (раздел 0): большая часть «газа» в журнале – проверки
# датчиков тестовым газом, а настоящие срабатывания единичны. Неисправность охраны встречается чаще, но это
# общее состояние системы охраны объекта, которое не указывает на конкретное оборудование и плохо прогнозируется на
# сутки; сервис показывает ее отдельно как фон и не смешивает с отказом. Для всех трех нужна вероятность по каждому
# объекту. Простейшая честная оценка – доля суток с событием на объекте за последний год, сжатая к общей доле:
# `(k + s · p0) / (n + s)`, где `k` – суток с событием, `n` – суток с данными за 365 суток строго до `D`, `p0` – общая
# доля по всем объектам за то же окно, `s` – сила сжатия. У объекта с короткой историей оценка близка к общей доле, с
# длинной – к своей. Силу `s` выбираем по Brier на валидации и сравниваем с частотным прогнозом за 30 суток и с
# константой.
#
# **Тонкость: что известно к полуночи.** Цель суток `D − 1` равна 1, если в эти сутки начался эпизод длительностью от
# минуты (потеря связи – от 10 минут). Эпизод, начавшийся в 23:59:30, в полночь еще идет, и длинный ли он, станет
# известно только после `D 00:00`. Все признаки модели учитывают это: эпизод относится к суткам, когда он стал известен
# длинным. А если брать историю прямо из меток целевой, в нее попадут такие эпизоды раньше срока. Посчитаем, сколько
# положительных суток затронуто: сравним метку суток `D − 1` с признаком «вчера был длинный эпизод» суток `D`, который
# построен по моменту известности (берем пары суток, где обе без маски).

