#    сложенный по группам каталога, показывает, какая доля «работы» модели приходится на группу;
# 2. **абляции** – переобучаем модель без группы признаков и смотрим, сколько теряет PR-AUC валидации. Каждый вариант,
#    включая полный, учим с тремя сидами и усредняем прогноз: иначе разница вариантов смешалась бы с шумом сида.
#    Выключения: вся история объекта (доли и счетчики эпизодов, часы с последнего эпизода); календарь и контекст
#    (выходной, день недели, производственный календарь – праздники, переносы, дни до нерабочего, доля тревог в
#    рабочее время, открытия дверей и люков, сезон подтоплений); статичные свойства (сколько у объекта каналов
#    каждого типа, пикетов). И обратный опыт – модель только на календаре и статичных свойствах, без какого-либо
#    знания о прошлом объекта. Для главного вопроса («сколько дает календарь») считаем интервал разности бутстрепом
#    по блокам 28 суток;
