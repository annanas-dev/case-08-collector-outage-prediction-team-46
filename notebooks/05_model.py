# %% [markdown]
# # 05. Модель: прогноз инцидентов на сутки вперед
#
# **Что делаем.** Каждые сутки в 00:00 сервис должен сказать диспетчеру по каждому объекту коллектора, насколько
# вероятен в ближайшие 24 часа отказ оборудования, пожар, подтопление или любой инцидент, и где на объекте искать.
# ТЗ требует вероятность, горизонт не меньше 24 часов, локацию и тип инцидента, а целевые Precision и Recall
# оставляет выбрать команде. Здесь мы обучаем модели градиентного бустинга (LightGBM) на готовой матрице признаков
# «объект × сутки», честно сравниваем их с простым частотным правилом и со случайным выбором, калибруем вероятности,
# выбираем уровни риска с ограничением нагрузки на диспетчера, объясняем отдельные прогнозы, ранжируем каналы и
# пикеты объекта и сохраняем все, что нужно сервису.
#
# **Главное правило оценки – будущее не подсматриваем.** Параметры подбираем только внутри 2019-2024 годов,
# калибровку и пороги проверяем по схеме «подобрали на одном году – проверили на следующем», а к первому полугодию
# 2026 года (тест) модели применяем один раз, когда все решения уже записаны. Честно оговоримся: этот период уже
# просматривался предыдущими версиями цепочки, поэтому защита от подгонки под тест здесь в том, что ни одно решение
# не принимается по нему (раздел 2). Каждая цифра качества стоит рядом с частотным прогнозом, постоянной вероятностью
# или случайным выбором.
#
# **Как устроен ноутбук.**
#
# 0. Задача и данные
# 1. Как будем мерить
# 2. Схема проверки
# 3. Первая модель на скользящих фолдах и шум сида
# 4. Подбор параметров
# 5. Финальная модель и валидация 2025
# 6. На что опирается модель: вклады, абляции, риск «предсказываем работы»
# 7. Калибровка
# 8. Уровни риска с потолком нагрузки
# 9. Газ, потеря связи и неисправность охраны: сглаженная частота
# 10. Объяснения прогноза и где искать на объекте
# 11. Тест 2026: один проход и артефакты для сервиса
# 12. Итоги для заказчика
#
# Все времена московские. «Инцидент» здесь – тревожный эпизод журнала СМВУ длительностью от минуты (потеря связи –
# от 10 минут), а не подтвержденное диспетчером происшествие: журнала ОДС в данных нет.

