def crossfit(p, y, half, method="Платт", fit_mask=None):
    """Прогноз, откалиброванный «на другой половине»: для недель половины h калибратор подогнан на половине 1 − h
    (и только на строках fit_mask, если задана). Возвращает массив той же длины."""
    out = np.full(len(p), np.nan)
    fit_mask = np.ones(len(p), bool) if fit_mask is None else fit_mask
    for h in (0, 1):
        fit = (half != h) & fit_mask
        out[half == h] = md.Calibrator.fit(p[fit], y[fit], method).predict(p[half == h])
    return out


