# дает инцидент, и в этот список попадает около трети отказов и 45 % любых инцидентов. Если диспетчер готов смотреть
# больше, уровень «высокий + средний» по любому инциденту – 13,7 объекта в сутки, 66,2 % инцидентов при точности
# 23,6 %. Обещание заказчику по точности и полноте – диапазоны по месяцам проверки вне выборки 2024 → 2025: отказ,
