#
# ## 4. Подбор параметров
#
# **Вопрос.** Можно ли заметно улучшить модель параметрами? Подбор – главный источник самообмана: из многих
# вариантов лучший на проверке почти всегда немного лучше по случайности, а теперь мы знаем, что одна только смена
# сида двигает PR-AUC на величину того же порядка, что и типичный выигрыш настройки. Поэтому каждый набор учим с
# тремя сидами и сравниваем средние, а правило выбора строгое и записано до запуска:
#
# - **опорный набор** – параметры из раздела 3;
# - набор-кандидат принимается, **только если в каждом из трех фолдов** его средний по сидам PR-AUC выше опорного
#   больше чем на два шума сида этого фолда (шум сида – стандартное отклонение PR-AUC между сидами, усредненное по
#   всем наборам цели в фолде). Из принятых берем лучший по среднему PR-AUC фолдов; если принятых нет, остаемся с
#   опорным;
# - число деревьев – медиана лучших итераций выбранного набора по фолдам и сидам.
#
# **Кандидаты различаются по целям.**
#
# - Для отказа и любого инцидента проверяем узкую окрестность одного сильного кандидата (63 листа, от 50 строк в
#   листе, шаг 0,03, 70 % признаков на дерево, L1 = 1 и L2 = 10, случайные пороги разбиения `extra_trees`,
#   сглаживание листьев): сам кандидат (набор 1) и по одному шагу в стороны (наборы 2-9: 31 и 127 листьев, от 20 и
#   от 100 строк в листе, L2 = 3 и 30, доля признаков 0,5 и 0,9); набор 0 – опорный. Это самые частые цели, у них самый маленький шум сида, и
#   небольшие, но устойчивые выигрыши здесь можно заметить.
# - Для пожара и подтопления – небольшой случайный поиск: 11 случайных наборов из сетки (число листьев 7-63, минимум
#   строк в листе 20-400, шаг 0,02-0,05, доля признаков 0,5-0,9, доля строк 0,7-0,9, L2 0-10). Эти цели самые шумные:
#   положительных суток в каждом проверочном году всего сотни, и PR-AUC от года к году прыгает сильнее, чем от
#   параметров. Правило «лучше в каждом фолде больше чем на два шума сида» особенно важно для подтопления: выигрыш
#   внутри шума сида выбирать нельзя.
#
# Каждый набор учим на каждом фолде с ранней остановкой по PR-AUC проверочного года (до 2 000 деревьев, остановка
# после 100 деревьев без улучшения). Средний PR-AUC фолдов здесь немного оптимистичен: ранняя остановка смотрела на
# тот же проверочный год. Для сравнения наборов между собой это неважно, а честные цифры дадут фолды с
# фиксированным числом деревьев ниже, валидация и тест.

# %%
C39 = md.PARAMS_CONFIG39
NEAR = [FIRST, C39] + [C39 | d for d in [{"num_leaves": 31}, {"num_leaves": 127}, {"min_data_in_leaf": 20},
                                         {"min_data_in_leaf": 100}, {"lambda_l2": 3.0}, {"lambda_l2": 30.0},
                                         {"feature_fraction": 0.5}, {"feature_fraction": 0.9}]]
SPACE = {"num_leaves": [7, 15, 31, 63], "min_data_in_leaf": [20, 50, 100, 200, 400],
         "learning_rate": [0.02, 0.03, 0.05], "feature_fraction": [0.5, 0.7, 0.9],
         "bagging_fraction": [0.7, 0.9], "lambda_l2": [0.0, 1.0, 10.0]}
rng = np.random.default_rng(42)
RANDOM = [FIRST]
while len(RANDOM) < 12:
    c = {k: rng.choice(v).item() for k, v in SPACE.items()} | {"bagging_freq": 1}
    if c not in RANDOM:
        RANDOM.append(c)
CANDIDATES = {"отказ": NEAR, "любой_инцидент": NEAR, "пожар": RANDOM, "подтопление": RANDOM}

t0 = time.time()
rows = []
for t in TARGETS:
    y = tr[f"цель_{t}"].to_numpy()
    for ci, params in enumerate(CANDIDATES[t]):
        for i_tr, i_va, year in FOLDS:
            for s in SEEDS_CV:
                _, best, ap = md.fit_lgbm_early(Xtr.iloc[i_tr], y[i_tr], Xtr.iloc[i_va], y[i_va], params,
                                                max_rounds=2000, patience=100, seed=s)
                rows.append({"цель": t, "набор": ci, "год": year, "сид": s, "pr_auc": ap, "лучшая_итерация": best})
search = pd.DataFrame(rows)
print(f"{len(search)} обучений с ранней остановкой, {(time.time() - t0) / 60:.1f} мин")

# %%
# шум сида: стандартное отклонение PR-AUC между сидами, среднее по наборам цели в фолде
noise = (search.groupby(["цель", "год", "набор"])["pr_auc"].std(ddof=1)
         .groupby(["цель", "год"]).mean().rename("шум_сида"))
per_fold = search.groupby(["цель", "набор", "год"])["pr_auc"].mean().unstack("год")
gain = per_fold.sub(per_fold.xs(0, level="набор"), level="цель")          # выигрыш к опорному по фолдам
margin = gain.div(2 * noise.unstack("год"), level="цель")                 # выигрыш в единицах «два шума сида»
summary = pd.DataFrame({"pr_auc_среднее": per_fold.mean(axis=1), "выигрыш_средний": gain.mean(axis=1),
                        "выигрыш_мин": gain.min(axis=1), "запас_мин": margin.min(axis=1)})
summary["принят"] = (summary["запас_мин"] > 1) & (summary.index.get_level_values("набор") != 0)

CHOSEN, rows = {}, []
for t in TARGETS:
    s = summary.loc[t].sort_values("pr_auc_среднее", ascending=False)
    ok = s[s["принят"]]
    ci = int(ok.index[0]) if len(ok) else 0
    it = int(search[(search["цель"] == t) & (search["набор"] == ci)]["лучшая_итерация"].median())
    CHOSEN[t] = {"набор": ci, "params": CANDIDATES[t][ci], "n_estimators": it}
    best = int(s.index[0])
