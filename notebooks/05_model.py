# ## 1. Как будем мерить
#
# Диспетчеру нужен короткий список объектов, где завтра вероятнее всего что-то случится, и честная вероятность для
# каждого. Отсюда метрики:
#
# - **PR-AUC** (площадь под кривой «точность-полнота») – главная метрика ранжирования для редких событий. У случайного
#   прогноза она равна доле положительных, у идеального – 1. ROC-AUC показываем для справки: при 1-5 % положительных
#   он выглядит хорошим даже у слабых моделей, потому что награждает за правильно отсеянные тысячи спокойных суток;
# - **точность и полнота в топ-5 и топ-10** – каждые сутки диспетчер смотрит 5 или 10 самых рискованных объектов из
#   примерно 75 с данными. Точность – доля объектов топа, где инцидент действительно случился, в среднем по суткам.
#   Полноту считаем двумя способами. «По суткам» – доля инцидентов суток, попавших в топ, в среднем по суткам с
#   инцидентами; она завышает картину, потому что сутки с одним пойманным инцидентом весят столько же, сколько сутки
#   с десятью. «Пулом» – все пойманные инциденты периода к всем инцидентам периода: это ответ на вопрос заказчика
#   «какую долю инцидентов мы увидим заранее», и обещания даем по ней;
# - **Brier** – средний квадрат разности между вероятностью и фактом (0 или 1). Меньше – лучше; он наказывает и за
#   плохое ранжирование, и за завышенные или заниженные вероятности;
# - **калибровка** – если среди всех случаев с прогнозом около 20 % инцидент случился примерно в 20 %, вероятности
#   можно показывать диспетчеру как есть;
# - **95 % интервалы** – бутстреп двумя способами, 1 000 повторов. По блокам из 28 суток: соседние сутки зависимы
#   (одна авария тянется днями, погода и работы идут неделями), поэтому пересэмплируем месяцы целиком. По объектам:
#   сутки одного объекта тоже зависимы (хронически сбоящий объект дает положительные сутки подряд), поэтому
#   пересэмплируем объекты целиком. Публикуем более широкий из двух интервалов: он честнее отражает, насколько
#   цифра могла бы быть другой на другом периоде или другом наборе объектов.
#
# Три ориентира, с которыми сравниваем модель: **частотный прогноз** (доля суток с целью на объекте за 30 суток),
# **константа** (доля положительных на обучении для всех строк) и **случайный выбор** при той же нагрузке (сколько
# инцидентов нашел бы диспетчер, проверяя столько же случайных объектов). Сначала посчитаем первые два на
# валидации 2025.

# %%
PRIOR = {t: tr[f"цель_{t}"].mean() for t in TARGETS + FREQ}    # константа: доля положительных на обучении


def scores(frame, t, p_col, prob_col=None) -> dict:
    """Метрики одной оценки риска: PR-AUC, ROC-AUC, точность и полнота (по суткам и пулом) в топ-5 и топ-10 суток –
    по порядку p_col; Brier – по вероятности prob_col (по умолчанию та же p_col)."""
    y, p = frame[f"цель_{t}"].to_numpy(), frame[p_col].to_numpy()
    prob = p if prob_col is None else frame[prob_col].to_numpy()
    top5, top10 = (md.precision_recall_at_top(frame, f"цель_{t}", p_col, k) for k in (5, 10))
    return {"pr_auc": md.average_precision(y, p), "roc_auc": roc_auc_score(y, p) if 0 < y.sum() < len(y) else np.nan,
            "точность_топ5": top5["precision"], "полнота_топ5": top5["recall"],
            "полнота_пулом_топ5": top5["recall_pooled"],
            "точность_топ10": top10["precision"], "полнота_топ10": top10["recall"],
            "полнота_пулом_топ10": top10["recall_pooled"], "brier": md.brier(y, prob)}


def with_const(frame):
    return frame.assign(**{f"константа_{t}": PRIOR[t] for t in TARGETS + FREQ})


METRIC_FMT = {"доля_положительных": "{:.2%}", "pr_auc": "{:.3f}", "roc_auc": "{:.3f}", "brier": "{:.4f}",
              **{f"{a}_топ{k}": "{:.1%}" for a in ["точность", "полнота", "полнота_пулом"] for k in (5, 10)}}
vc = with_const(va)
rows = []
for t in TARGETS + FREQ:
    for role, col in [("частотный", f"базовый_прогноз_{t}"), ("константа", f"константа_{t}")]:
        rows.append({"цель": t, "прогноз": role, "доля_положительных": vc[f"цель_{t}"].mean(), **scores(vc, t, col)})
base_val = pd.DataFrame(rows).set_index(["цель", "прогноз"])
display(base_val.style.format(METRIC_FMT))

