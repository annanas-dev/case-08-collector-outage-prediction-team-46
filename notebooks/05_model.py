def same_load(frame, t, flag, base_col) -> dict:
    """Попадания модели (строки flag), частотного прогноза при той же нагрузке в каждые сутки и случайного выбора."""
    y_col = f"цель_{t}"
    f = frame[["день", "ид_объект", y_col, base_col]].assign(_f=np.asarray(flag))
    m = f.groupby("день")["_f"].sum()
    fs = f.sort_values(["день", base_col, "ид_объект"], ascending=[True, False, True], kind="mergesort")
    bflag = fs.groupby("день").cumcount().to_numpy() < fs["день"].map(m).to_numpy()
    per_day = f.groupby("день")[y_col].agg(["size", "sum"])
    total = f[y_col].sum()
    hits = {"модель": f.loc[f["_f"], y_col].sum(), "частотный": fs[y_col].to_numpy()[bflag].sum(),
            "случайно": (m * per_day["sum"] / per_day["size"]).sum()}
    return {"цель": t, "помечено_объекто_суток": int(f["_f"].sum()), "инцидентов_всего": int(total),
            **{f"попаданий_{k}": v for k, v in hits.items()},
            **{f"полнота_{k}": v / total for k, v in hits.items()}}


