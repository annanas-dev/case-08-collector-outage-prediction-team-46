# **Где искать.** Для отказа сервис дает три канала и три пикета объекта по давности и частоте прошлых отказов.
# Хотя бы один канал из тройки отказывает в эти сутки в 51,3 % случаев (наугад 16,9 %), канал первого отказа стоит
# первым в 21,1 % (наугад 3,4 %).
#
# **Газ, потеря связи, неисправность охраны.** Прогноза на сутки нет: ни история объекта, ни частотные правила не
# лучше константы по Brier. Сервис показывает фоновую вероятность объекта (сглаженная частота за год). Газ после
# снятия проверок ППР почти исчез из данных (17 суток в валидации, 15 в тесте) и предсказанию на сутки не поддается.
#
# **Ограничения.**
#
# - Прогнозируется тревожный эпизод журнала СМВУ, а не подтвержденный инцидент: журнала ОДС с решениями диспетчеров
#   нет, и часть «инцидентов» – ложные срабатывания и следы работ.
# - Тестовый период уже просматривался предыдущими версиями цепочки. Решения этого ноутбука приняты только по фолдам и
#   валидации, но независимой оценкой будет только следующее полугодие работы сервиса.
# - Маска ППР АКМ снимает только работы по метановой аппаратуре. Окна прошлых лет восстановлены по журналу, а не по
#   документам, и могут быть неточны по краям (для этого запас ±3 суток); окна 2026 года взяты из графика.
# - Календарь дает 2-15 % PR-AUC (у отказа 0,040 [0,019; 0,057]): в будни тревог больше, потому что в коллекторах
#   работают бригады. Прогноз к календарю не сводится (без истории объекта PR-AUC теряет 21-31 %), но отделить прочие
#   работы от угроз без их графика нельзя. В субботы и воскресенья вероятности занижены на 12-24 %.
# - Доля инцидентов растет: калибровка по 2025 году занижает уровень 2026 года на 4-15 %, а нагрузка в худшем месяце
#   выходит за потолок в 1,1-1,9 раза. Калибровку и пороги нужно пересматривать по последним месяцам (например,
#   ежеквартально по той же процедуре), а модели – переобучать с добавлением 2025 года.
# - Интервалы широкие (у отказа на тесте PR-AUC от 0,20 до 0,41): 78 объектов, и несколько хронически сбоящих дают
#   заметную долю инцидентов. Устойчиво положительна разность с частотным прогнозом, а не сама величина PR-AUC.
# - Около половины отказов остаются на уровне «низкий» (в валидации 388 из 819): это цена потолка нагрузки; часть из
#   них – внезапные отказы на объектах без недавней истории, которые по журналу не предсказать.
# - Хронически сбоящие объекты дают ложные тревоги в спокойные дни: для них полезнее рекомендация ТО, чем ежедневный
#   прогноз.
# - По подтоплению 89 положительных суток в тесте и 116 в валидации – меньше, чем нужно для устойчивой оценки: PR-AUC
#   теста от 0,07 до 0,31, точность уровня «высокий» по месяцам от 0 до 46 %. Параметры модели не подбирались,
#   потому что выигрыш не выходил за шум. Прогноз подтопления – список наблюдения, а не обещание точности.
#
# **Что улучшит прогноз.** Журнал ОДС (подтвержденные инциденты и ложные срабатывания как метка), график прочих
# плановых и аварийных работ помимо ППР АКМ (отделить работы от угроз, особенно для газа и пожара), история ремонтов и
# замен оборудования по каналам (точнее «где искать»), паспортные данные оборудования, погода для подтоплений.
