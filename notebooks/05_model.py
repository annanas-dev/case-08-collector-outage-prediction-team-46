def p_any(N, m, k):
    """Вероятность, что среди k каналов, взятых наугад из N, есть хотя бы один из m."""
    miss = np.ones(len(N))
    for i in range(k):
        miss *= np.clip((N - m - i) / (N - i), 0, 1)
    return 1 - miss


