# %% [markdown]
# # 01. Предобработка журнала событий СМВУ, 2019-2026
#
# ## Что за данные и зачем их готовить
#
# Москоллектор передал нам журнал событий системы мониторинга и управления (СМВУ) инженерных коллекторов.
# Каждая строка журнала – одно сообщение от одного канала датчика: газоанализатор прислал очередной замер,
# дверь открылась, насос включился, дымовой датчик перешел в «Неисправен». Журнал разбит на восемь годовых
# CSV-файлов (2019 – первая половина 2026 года), вместе около 16 GB и примерно 313 млн строк. К нему приложены
# справочники: каналы датчиков (тип датчика, название, объект), дерево объектов и словарь состояний, а также
# пример журнала за один день, 2026-08-01, в том виде, в котором система будет получать данные в работе.
#
# Прежде чем искать в журнале предвестники инцидентов, нужно убедиться, что сам журнал читается однозначно:
# в нем нет повторов, которые завысят счетчики, нет «мусорных» строк, флаг тревоги понимается одинаково во всех
# годах, а значения датчиков разобраны на числа и состояния. Этот ноутбук делает ровно это: один раз читает
# все CSV, находит в них особенности формата, проверяет каждую на данных, очищает журнал и сохраняет его
# в компактное хранилище Parquet. Все дальнейшие исследования работают только с этим хранилищем.
#
# Про содержание мы на этом этапе ничего не выбрасываем. По словам заказчика, в 2021 году внедрялась новая
# СМВУ и какое-то время старая и новая системы работали параллельно. Как это отразилось на журнале, будем
# разбираться при его исследовании, а здесь сохраняем все периоды целиком и убираем только то, что
# является дефектом выгрузки, а не событием.
#
# *Техническое примечание.* Для пробного прогона годы можно ограничить переменной окружения
# `ETL_YEARS` (например, `ETL_YEARS=2019`). Все цифры в тексте относятся к полному прогону по всем годам.

