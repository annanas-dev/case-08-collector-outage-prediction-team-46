# %% [markdown]
# ## 1. Справочники каналов и объектов
#
# Журнал ссылается на канал только номером `ид_канала_данных`. Чтобы понимать, что это за датчик и где он
# стоит, к каналу нужно подтянуть справочник каналов (тип датчика, название, объект) и дерево объектов.
# Посмотрим на оба справочника.

# %%
channels_raw = pd.read_csv(DATASETS_DIR / "справочник_каналов_датчиков.csv")
objects_raw = pd.read_csv(DATASETS_DIR / "справочник_объектов_диспетчер.csv")
print("каналов:", len(channels_raw), "| уникальных ид_канала_данных:", channels_raw["ид_канала_данных"].nunique())
print("объектов:", len(objects_raw))
channels_raw.head(3)

# %%
levels = ["иерархия_уровень", "вид_объекта"]
(objects_raw.groupby(levels).size().rename("количество_объектов").to_frame()
 .join(channels_raw.merge(objects_raw, on="ид_объект").groupby(levels).size().rename("каналов"))
 .fillna(0).astype(int).reset_index())

# %% [markdown]
# Объекты образуют дерево из трех уровней: наверху один район по эксплуатации, под ним 16 объектов второго
# уровня, а под ними 78 объектов третьего уровня. Все 11 485 каналов привязаны к объектам третьего уровня,
# поэтому объект третьего уровня – естественная единица, для которой будем строить прогноз, а его родитель
# второго уровня дает группировку крупнее.
#
# Координат у датчиков нет. Но в названии канала часто стоит пикет – отметка расстояния вдоль коллектора,
# например `ГАЗ Д26 ПК746` или `Темп. ВШ ПК88,5`. Это единственная доступная локация внутри объекта, поэтому
# вытаскиваем номер пикета из названия. Формат записи неоднороден: встречаются нижний регистр, пробел после
# «ПК», дробная часть через запятую и диапазоны вида `ПК86-85` (берем первое число).

# %%
names = channels_raw["название_датчика"]
pk_examples = pd.concat([
    names[names.str.contains(r"ПК\d+,\d", regex=True)].head(2),
    names[names.str.contains(r"пк", regex=False)].head(2),
    names[names.str.contains(r"ПК\d+-\d", regex=True)].head(2),
    names[~names.str.contains(r"пк", case=False)].head(3),
])
pd.DataFrame({"название_датчика": pk_examples, "пикет": pk_examples.map(etl.extract_pk)})

# %% [markdown]
# Функция `etl.build_channels` объединяет справочник каналов с деревом объектов (объект канала и название его
# родителя) и добавляет столбец `пикет`. Столбец `тег_инженерной_системы` удаляем: это уникальный технический
# код канала, организаторы разрешили его не использовать.

# %%
channels = etl.build_channels(channels_raw, objects_raw)
print("каналов без объекта:", channels["диспетчерское_название_объекта"].isna().sum())
print("доля каналов с пикетом:", round(channels["пикет"].notna().mean(), 3))
(channels.assign(без_пикета=channels["пикет"].isna())
 .groupby("тип_датчика")["без_пикета"].agg(каналов="size", каналов_без_пикета="sum", доля_без_пикета="mean")
 .round(3).sort_values("каналов_без_пикета", ascending=False))

# %%
channels.to_parquet(PROCESSED_DIR / "channels.parquet", index=False)
channels.head(3)

