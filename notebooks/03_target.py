# ## 8. Предсказуемость
#
# Последний и главный критерий: можно ли вообще прогнозировать цель на сутки вперед. Те же две проверки, что
# в разделе 6.4 (функция `predictability`), на сетке «объект × сутки», маскированные дни исключены:
# - **подъем вероятности**: во сколько раз вероятность положительного дня выше, если на объекте этот класс уже
#   был за последние 7 дней: P(y = 1 | был за 7 дней) / P(y = 1). Значение 1 – прошлое ничего не говорит о будущем;
# - **частотный прогноз** «доля дней с этим классом на объекте за прошлые 30 дней» (строго до дня прогноза)
#   на 2025 году: PR-AUC (площадь под кривой точность-полнота) против доли положительных, которая
#   равна PR-AUC случайного прогноза. Это же будет baseline для моделей.
#
# Те же проверки для отвергнутых вариантов: цели по флагу и по словарю и «отказ вне контекста работ»
# (без открытия двери или люка за 3 часа), чтобы выбор был подтвержден и предсказуемостью. И для неисправности
# охраны: отдельно, в составе отказа и в составе «любого инцидента» – так видно, что она делает с целью.

