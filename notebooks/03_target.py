# %% [markdown]
# **Наблюдение.** Таких дней 433 на 19 объектах, то есть у каждого объекта, чьи газовые каналы пишут в журнал.
# Это не редкость, а 51-66 дней за каждый полный год, и они устроены одинаково: 97,2 % приходятся на будни,
# первая запись «Обнаружен газ» – почти всегда утром (08:00-10:59 – 343 из 433), а газ сообщают, как правило,
# сразу все газовые каналы объекта (медиана доли 1,00, все каналы – в 65,4 % дней). Настоящая утечка вряд ли
# охватывает все датчики объекта сразу и вряд ли знает расписание рабочего дня.
#
# **Вопрос.** Повторяются ли вспышки у одного объекта из года в год? Если это обслуживание, оно должно идти
# по годовому плану: у каждого объекта в свой месяц. Соберем вспышки объекта в эпизоды (функция
# `annanas.maintenance.detect_windows`): дни объекта по порядку идут в один кластер, пока следующий день не дальше
# 21 суток от предыдущего и 25 суток от первого, одиночный день окном не считается. Окно работ –
# от первой вспышки кластера до последней, но не короче 16 суток: если это работы с датчиками, газ виден при
# возврате датчиков и при сдаче, а начало работ (демонтаж) им не отмечено. Параметры подобраны по графику
# работ, который разберем ниже, и потому проверка детектора на этом графике будет оптимистичной.

# %%
det = mt.detect_windows(burst)
det["год"], det["месяц"] = det["конец"].dt.year, det["конец"].dt.month
in_cluster = {(o, d) for o, a, b in zip(det["ид_объект"], det["начало"], det["конец"]) for d in pd.date_range(a, b)}
print(f"окон: {len(det)} на {det['ид_объект'].nunique()} объектах; вспышек внутри окон: "
      f"{np.mean([k in in_cluster for k in zip(burst['ид_объект'], burst['день'])]):.1%}")
display(det.pivot_table(index="ид_объект", columns="год", values="месяц",
                        aggfunc=lambda s: ", ".join(map(str, s))).fillna(""))


def typical_month(s):
    return s.value_counts().index[0]


dev = det.groupby("ид_объект")["месяц"].transform(lambda s: ((s - typical_month(s) + 6) % 12) - 6)
yrs = det.groupby("ид_объект")["год"].nunique()
print(f"окон в пределах ±1 месяца от типичного месяца объекта: {(dev.abs() <= 1).mean():.1%}; "
      f"объектов с окнами хотя бы в 5 разных годах: {(yrs >= 5).sum()} из {len(yrs)}")

