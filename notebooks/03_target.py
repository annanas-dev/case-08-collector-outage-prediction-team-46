def by_year(name, build):
    """Эпизоды по годам с перекрытием в сутки, кэш в EP_DIR/name/<год>.parquet."""
    for y in YEARS:
        lo, hi = pd.Timestamp(y, 1, 1), pd.Timestamp(y + 1, 1, 1)

        def one(lo=lo, hi=hi, y=y):
            ev = events.filter(F.col("год").between(y - 1, y + 1)
                               & (F.col("дата_время") >= lo - pd.Timedelta(days=1))
                               & (F.col("дата_время") < hi + pd.Timedelta(days=1)))
            return build(ev).filter((F.col("начало") >= lo) & (F.col("начало") < hi))
        agg.build_or_load(str(y), one, EP_DIR / name, spark)
    return spark.read.parquet(*[str(EP_DIR / name / f"{y}.parquet") for y in YEARS])


