# - **вариант 2** – для газа маскировать те же сутки, а для остальных целей не маскировать день, а убрать из
#   разметки только эпизоды внутри окна, начавшиеся в рабочее время будних дней (пн-пт 8:00-17:59): вечерние,
#   ночные и выходные эпизоды в окнах остаются.
#
# Критерии – объем положительных, который остается, и предсказуемость. Предсказуемость меряем двумя простыми
# проверками на сетке «объект × сутки» (функция `predictability`, она же дальше используется в разделе 8):
# **подъем вероятности** – во сколько раз вероятность положительного дня выше, если на объекте этот класс уже был
# за последние 7 дней, P(y = 1 | был за 7 дней) / P(y = 1); и **частотный прогноз** – доля дней с этим классом на
# объекте за прошлые 30 дней (строго до дня прогноза), для которого на 2025 году считаем PR-AUC (площадь под
# кривой точность-полнота) и делим на долю положительных (PR-AUC случайного прогноза). Маскированные дни не
# входят ни в оценку, ни в историю частотного прогноза.

# %%
def predictability(y_col, frame):
    """Подъем за 7 дней (обучение 2019-2024 и 2025) и PR-AUC частотного прогноза на 2025."""
    f = frame.sort_values(["ид_объект", "день"])
    y = f[y_col].where(f["маска"].isna())  # маскированные дни – пропуск, в историю не идут
    g = y.groupby(f["ид_объект"])
    past7 = g.transform(lambda s: s.shift(1).rolling(7, min_periods=1).max())
    score = g.transform(lambda s: s.shift(1).rolling(30, min_periods=7).mean())
    out = {}
    for name, sel in [("2019-2024", f["день"] < "2025-01-01"), ("2025", f["день"].dt.year == 2025)]:
        m = sel & y.notna() & past7.notna()
        base = y[m].mean()
        out[f"доля_{name}"] = base
        out[f"подъем_7д_{name}"] = y[m & (past7 == 1)].mean() / base if base > 0 else np.nan
    m = (f["день"].dt.year == 2025) & y.notna() & score.notna()
    out["положительных_2025"] = int(y[m].sum())
    out["PR_AUC_2025"] = average_precision(y[m], score[m])
    out["PR_AUC_к_доле"] = out["PR_AUC_2025"] / y[m].mean()
    return out


