# (кроме марта 2022), 5675 и 5657 – май и июнь каждый год с 2022. 84,2 % окон отстоят от типичного месяца своего
# объекта не больше чем на месяц, у 17 из 19 объектов окна есть хотя бы в пяти разных годах. Некоторые объекты
# сдвигали свой месяц (3388: июнь в 2019-2020, март с 2021; 4543: февраль-март до 2023, октябрь с 2024).
#
# **Гипотеза.** Одновременный газ на большинстве датчиков объекта, в рабочее время будних дней, раз в год
