# %% [markdown]
# Так и есть: в днях без записей положительных меток нет вообще. Значит, правило «нет записей за день» – это
# фактически правило «оставить только дни, в которые что-то происходило».
#
# **Что используем вместо него** (функция `annanas.target.connection_mask`). Маска ставится только по записям
# строго до 00:00 дня D:
# - **«объект не подключен»** – до дня D у объекта не было ни одной записи: он еще не заведен в СМВУ, и прогноз
#   для него не нужен;
# - **«объект не на связи»** – объект постоянно пишущий (медиана записей в сутки за 30 предыдущих дней больше
#   200, дни без записей считаются нулями) и за все сутки D − 1 не написал ничего. Для такого объекта сутки
#   тишины – это обрыв связи с контроллером, а не спокойный день, и за день D метке нет доверия. Порог 200
#   (больше 8 записей в час) отделяет объекты с постоянным потоком замеров от объектов, которые пишут по
#   событию (таблица выше).
#
# Тихий день подключенного объекта, который пишет редко, не маскируется: это обычный отрицательный пример.
#
# **Проверка 2.** Сколько объекто-суток закрывает каждое правило и как меняется доля положительных. Сравниваем
# на днях, не закрытых общими масками.

