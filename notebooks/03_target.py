def flag_table(df):
    def part(mask, suffix):
        g = df[mask].groupby(["тип_датчика", "состояние"])[["количество_событий", "количество_тревожных"]].sum()
        return pd.DataFrame({f"записей_{suffix}": g["количество_событий"],
                             f"доля_флага_{suffix}": g["количество_тревожных"] / g["количество_событий"]})
    t = pd.concat([part(df["период"] == "до", "до"), part((df["период"] == "до") & df["ночь"], "до_ночью"),
                   part(df["период"] == "после", "после")], axis=1)
    t.insert(0, "класс", [ep.state_class(т, с) for т, с in t.index])
    return t.fillna({c: 0 for c in t.columns if c.startswith("записей")})


