# %% [markdown]
# ### 6.4 Плановые работы аппаратуры контроля метана
#
# **Наблюдение.** В разделе 6.2 все газовые датчики объекта 5122 одновременно сообщили «Обнаружен газ»
# 6 ноября 2025 года в рабочее время. Если это разовый случай, достаточно замаскировать один объекто-день. Но
