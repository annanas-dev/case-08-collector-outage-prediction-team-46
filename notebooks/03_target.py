def labels_from_hits(hits, cls, t=T_FLAP):
    x = hits[(hits["класс"] == cls) & (hits[f"от_{t}_с"] > 0)][["ид_объект", "день"]].drop_duplicates()
    return set(zip(x["ид_объект"], x["день"]))


variants = labels[["ид_объект", "день", "маска"] + TARGETS].copy()
for s in ("флаг", "словарь"):
    for c in ["отказ", "подтопление", "пожар", "газ"]:
        hit = labels_from_hits(HITS[s], c)
        variants[f"{c} ({s})"] = [int((o, d) in hit) for o, d in zip(variants["ид_объект"], variants["день"])]
for c in ["отказ", "пожар"]:
    for t in (0, 600):
        hit = labels_from_hits(HITS["пары"], c, t)
        variants[f"{c} от {t} с (пары)"] = [int((o, d) in hit) for o, d in zip(variants["ид_объект"], variants["день"])]
off = final_eps[~((final_eps["начало"].dt.dayofweek < 5) & final_eps["начало"].dt.hour.between(8, 17))]
for c in ["пожар", "газ", "подтопление"]:
    x = off[off["класс"] == c]
    hit = set(zip(x["ид_объект"], x["начало"].dt.floor("D")))
    variants[f"{c} вне рабочего времени (пары)"] = [int((o, d) in hit) for o, d in
                                                    zip(variants["ид_объект"], variants["день"])]
no_work = faults[~faults["открытие_за_3_ч"].fillna(False)].assign(день=lambda d: d["начало"].dt.floor("D"))
