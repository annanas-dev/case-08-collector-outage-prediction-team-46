#
# **Гипотеза.** Дискретный датчик пишет в журнал только тогда, когда меняется его состояние. Если за сутки на
# объекте ничего не сработало и ничего не вернулось в норму, записей не будет, и это не пропуск данных, а
# как раз обычный спокойный день без инцидента. У правила «нет записей за день» есть и более серьезный дефект:
# оно решает, оставить ли день, по записям **самого дня D**, то есть по окну, которое мы прогнозируем. В 00:00
