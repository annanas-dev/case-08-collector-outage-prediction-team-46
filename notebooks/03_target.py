def by_slot(part):
    """Доля флага по слотам «ночь / день 9-16 / прочие» × рабочий день."""
    x = part.assign(рабочий_день=part["день"].dt.dayofweek < 5,
                    часы=np.select([part["час_суток"] < 7, part["час_суток"].between(9, 16)],
                                   ["ночь 0-6", "день 9-16"], "прочие"))
    g = x.groupby(["часы", "рабочий_день"])[["количество_событий", "количество_тревожных"]].sum()
    return g.assign(доля_флага=g["количество_тревожных"] / g["количество_событий"])[["количество_событий", "доля_флага"]]


display(pd.concat({"до смены": by_slot(before), "после смены": by_slot(after)}, axis=1).round(3))

