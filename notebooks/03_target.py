def average_precision(y, score) -> float:
    """PR-AUC (average precision): площадь под кривой точность-полнота, одинаковые оценки – один порог."""
    d = pd.DataFrame({"y": np.asarray(y, dtype=float), "s": np.asarray(score, dtype=float)}).dropna()
    g = d.groupby("s", sort=True)["y"].agg(["sum", "count"]).iloc[::-1]
    tp, cnt = g["sum"].cumsum(), g["count"].cumsum()
    recall = tp / d["y"].sum()
    return float((recall.diff().fillna(recall) * (tp / cnt)).sum())


