def dur_bin(col="длительность_с"):
    e = F.when(F.col(col).isNull(), "не закрыт")
    for lo_, hi_, name in BINS:
        e = e.when(F.col(col) >= lo_ if hi_ is None else F.col(col).between(lo_, hi_), name)
    return e


