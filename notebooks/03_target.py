# всем журнале: объект × сутки, где «Обнаружен газ» было хотя бы на половине газовых каналов объекта (из тех,
# что вообще пишут в журнал), а первая такая запись за сутки пришлась на 07:00-17:59. Функция
# `annanas.maintenance.gas_burst_days` считает это в Spark по всему журналу, результат кэшируется
# в `datasets/processed/maintenance/`. Дальше такие дни называем вспышками газа.

