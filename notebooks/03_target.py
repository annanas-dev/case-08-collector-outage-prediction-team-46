variants["отказ вне работ (пары)"] = [int((o, d) in nw) for o, d in zip(variants["ид_объект"], variants["день"])]
rows = {}
variants["отказ вместе с неисправностью охраны (пары)"] = variants[["цель_отказ", "цель_неисправность_охраны"]].max(axis=1)
variants["любой инцидент вместе с неисправностью охраны"] = variants[["цель_любой_инцидент",
                                                                       "цель_неисправность_охраны"]].max(axis=1)
for c in FORECAST + ["проникновение", "неисправность_охраны", "любой_инцидент"]:
    rows[f"{c} (пары)" if c not in ("потеря_связи", "любой_инцидент") else c] = predictability(f"цель_{c}", variants)
for col in [c for c in variants.columns if "(" in c]:
    rows[col] = predictability(col, variants)
rows["любой инцидент вместе с неисправностью охраны"] = predictability(
    "любой инцидент вместе с неисправностью охраны", variants)
