# 2. Из записей в эпизоды
# 3. Дребезг: какие эпизоды слишком короткие, чтобы быть инцидентом
# 4. Работы бригад и ложные отказы
# 5. Потеря связи
# 6. Маски и эпохи: какие дни нельзя использовать, включая плановые работы аппаратуры контроля метана
