# **Вся система.** `других_объектов_<класс>_1д` – на скольких других объектах вчера был длинный эпизод класса.
# Гипотеза: общесистемные сбои (питание, связь) задевают многие объекты сразу.
#
# **Соседи.** `соседи_дней_<класс>_7д` – сумма дней с эпизодами класса за 7 суток у объектов того же родителя
# (`fe.sibling_sums`, сам объект не входит). Гипотеза: соседние участки коллектора делят воду, питание, бригады.
#
# **Постоянные свойства.** Число каналов объекта всего и по основным типам, число различных пикетов. Они описывают
# размер и оснащенность объекта. Справочник – это снимок на сегодня, а не история, поэтому в ранние годы он может
# расходиться с реальностью; зато от будущих событий журнала он не зависит.

# %%
def describe_system(c):
    fixed = {"период_смву_код": "период СМВУ: 0 – до перехода, 1 – переход, 2 – после",
             "эпоха_флага_код": "эпоха разметки флага: 1 – после 2025-10-29",
             "доля_вне_справочника_7д": "доля записей журнала от каналов вне справочника за 7 суток (вся система)",
             "каналов_всего": "каналов объекта в справочнике", "число_пикетов": "разных пикетов у каналов объекта"}
    if c in fixed:
        return fixed[c]
    for pat, text in [(r"^других_объектов_(.+)_1д$", "других объектов с длинным эпизодом класса «{0}» вчера"),
                      (r"^соседи_дней_(.+)_7д$", "дней с эпизодом класса «{0}» за 7 суток у объектов того же родителя"),
                      (r"^каналов_(.+)$", "каналов типа «{0}» у объекта")]:
        m = re.match(pat, c)
        if m:
            return text.format(*m.groups())
    return c


