# ### 0.3 Когда событие становится известным
# Правило «только до `D 00:00`» надо применить к каждому событию аккуратно. Эпизод, начавшийся вчера в 23:59:30,
# в полночь еще идет: длится он минуту или пять секунд, станет известно только сегодня. А целевая считает только
# эпизоды длиннее минуты. Поэтому у каждого эпизода вводим **момент известности**:
#
# - длинный эпизод (от минуты, или незакрытый) становится известным длинным через минуту после начала;
# - короткий эпизод (дребезг, меньше минуты) известен как короткий в момент своего конца;
# - для потери связи порог – 10 минут: длинный эпизод известен через 10 минут после начала, короткий – через
#   минуту после последней минуты.
#
# Все суточные ряды по эпизодам раскладываем по дню момента известности. Признак суток `D` видит только дни до
# `D`, то есть только события, известные до `D 00:00`. Сутки с маской исключаем и из истории: например, «переход
# СМВУ» и «плановые работы АКМ» порождают массовые артефактные эпизоды, которые не должны выглядеть как
# «проблемное прошлое» объекта.

