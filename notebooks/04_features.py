meas = (daily_channel[daily_channel["класс_записи"] == "измерение"]
        .merge(channels[["ид_канала_данных", "ид_объект", "тип_датчика"]], on="ид_канала_данных")
        .query("тип_датчика in @TEMP or тип_датчика in @GAS"))
tails = []
for тип, g in meas.groupby("тип_датчика"):
    lo = g["минимум_значения"][g["минимум_значения"] <= g["минимум_значения"].quantile(0.01)].round(2)
    hi = g["максимум_значения"][g["максимум_значения"] >= g["максимум_значения"].quantile(0.99)].round(2)
    for side, v in [("нижний 1 % минимумов", lo), ("верхний 1 % максимумов", hi)]:
        vc = v.value_counts().head(6)
        tails.append({"тип_датчика": тип, "хвост": side, "канало_суток_в_хвосте": len(v),
                      "частые_значения (канало-суток)": ", ".join(f"{k:g} ({c})" for k, c in vc.items())})
display(pd.DataFrame(tails))
print(f"канало-суток замеров: температура {n((meas['тип_датчика'] == TEMP).sum())}, газ {n((meas['тип_датчика'] == GAS).sum())}")

