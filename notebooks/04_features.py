# ### 0.4 Как оцениваем признак
# У каждой группы признаков одна и та же проверка, на **обучающей выборке без масок**:
#
# - **одиночный сигнал**: берем признак как готовую оценку риска (чем больше, тем рискованнее, или наоборот – берем
#   лучшую из двух сторон) и считаем PR-AUC – площадь под кривой «точность-полнота». У случайной оценки PR-AUC равен
#   доле положительных, поэтому смотрим на **подъем**: PR-AUC, деленный на долю положительных на тех же строках.
#   Подъем 1 – сигнала нет, 2 – признак в одиночку вдвое лучше случайного ранжирования. PR-AUC выбран потому, что
#   цели редкие (от 0,8 до 4,9 % суток обучения), а для редких событий важна точность в верхушке списка;
# - **устойчивость**: PSI (population stability index) – насколько распределение признака сдвинулось от обучения
#   к валидации, и отдельно – до и после смены разметки флага 2025-10-29 внутри 2025-2026 годов. PSI до 0,1 –
#   сдвига нет, 0,1-0,25 – умеренный, больше 0,25 – сильный.
#
# Все признаки складываем в одну таблицу `X` в порядке строк сетки, а для каждого запоминаем группу, окно и смысл:
# из этого в разделе 10 получится каталог.

