# ## 5. Телеметрия: газ и температура
#
# **Почему группа может работать.** У газовых датчиков и датчиков температуры кроме состояний есть числовые замеры.
# Рост концентрации газа или необычная температура могут предшествовать тревоге, а молчание датчика – его отказу.
# Но сначала нужно отделить настоящие значения от служебных кодов: контроллер при сбое пишет в поле значения
# фиксированные числа, и если принять их за замер, «−127 градусов» станет самым сильным «сигналом».
#
# ### 5.1 Служебные коды
# **Проверка.** Берем суточные минимумы и максимумы каналов и смотрим, какие точные значения чаще всего стоят на
# хвостах: в нижнем 1 % минимумов и верхнем 1 % максимумов. Настоящий замер на хвосте размазан по многим значениям,
# код – это одно и то же число сотни раз.

# %%
