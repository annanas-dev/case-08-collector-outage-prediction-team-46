# %% [markdown]
# # 04. Признаки: что модель будет знать о прошлом объекта
#
# **Что делаем.** Модель должна в 00:00 каждых суток сказать для каждого объекта коллектора, насколько вероятен
# в ближайшие 24 часа отказ оборудования, пожар, подтопление или любой инцидент, а для редких классов (газ, потеря
# связи, неисправность охраны) достаточно фоновой частоты. Для этого ей нужны признаки:
# числа, которые описывают состояние объекта к моменту прогноза. Здесь мы строим такие признаки из журнала событий
# СМВУ, для каждой группы проверяем, есть ли в ней сигнал, отбираем рабочий набор и собираем итоговую матрицу
# «объект × сутки» для обучения. Саму модель здесь не обучаем: единственный прогноз в этом ноутбуке – простейший
# частотный, нижняя планка, которую модель обязана обойти.
#
# **Главное правило – никакого знания о будущем.** Признак на сутки `D` вычисляется только из того, что было
# известно до `D 00:00`. Если хоть один признак «подсмотрит» события самих суток `D`, модель научится узнавать
# инцидент по его же следам и покажет на истории блестящую точность, которой в работе не будет. Поэтому правило
# закладываем в сами функции расчета, а в разделе 9 проверяем тремя независимыми способами.
#
# **Как устроен ноутбук.**
#
# 0. Задача, данные и способ оценки признака
# 1. Горизонт памяти: какие окна брать
# 2. История объекта по классам инцидентов, часы с последнего эпизода
# 3. Каналы: сколько датчиков сбоит и как долго
# 4. Потеря связи и активность каналов
# 5. Телеметрия: газ и температура
# 6. Контекст работ, календарь, производственный календарь и плановые работы АКМ
# 7. Подтопление: насосы
# 8. Эпохи, вся система, соседи, постоянные свойства объекта
# 9. Проверка утечки
# 10. Отбор признаков и каталог
# 11. Итоговая матрица и частотный прогноз
# 12. Итоги
#
# Код построения признаков (строители групп `build_*`, сборка `build_all`, обрезка данных на полночь `cut` и их
# вспомогательные функции) лежит в пакете проекта, в модуле `annanas.inference.features`: тем же кодом сервис
# считает прогноз на сутки. Здесь мы вызываем его группа за группой и перед каждым вызовом объясняем, что строит
# группа и почему. Все времена московские.

