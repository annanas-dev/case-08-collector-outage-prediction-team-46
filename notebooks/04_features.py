X = pd.DataFrame(index=grid.index)
CATALOG, SIGNAL = {}, {}


def window_of(col):
    m = re.search(r"_(\d+)д(?:_|$)", col)
    return int(m.group(1)) if m else None


def add(frame, group, meaning):
    """Кладет признаки из frame (строки в порядке сетки) в X; meaning – строка или функция имени признака."""
    global X
    cols = [c for c in frame.columns if c not in KEY]
    X = pd.concat([X.drop(columns=[c for c in cols if c in X]),
                   pd.DataFrame({c: np.asarray(frame[c], dtype="float32") for c in cols}, index=X.index)], axis=1)
    for c in cols:
        CATALOG[c] = {"группа": group, "окно": window_of(c), "смысл": meaning(c) if callable(meaning) else meaning}
    return cols


def evaluate(cols):
    """Подъем PR-AUC по модельным целям на обучении, пропуски, PSI обучение → валидация и до → после эпохи флага."""
    out = pd.DataFrame(index=cols)
    for t in MODEL_TARGETS:
        st = fe.signal_table(X.loc[TRAIN, cols], Y[t][TRAIN]).set_index("признак")
        out[f"подъем_{t}"] = st["подъем_pr_auc"]
    out["доля_пропусков"] = X.loc[TRAIN, cols].isna().mean()
    out["psi_валидация"] = [fe.psi(X.loc[TRAIN, c], X.loc[VALID, c]) for c in cols]
    out["psi_эпоха"] = [fe.psi(X.loc[LATE & ~AFTER, c], X.loc[LATE & AFTER, c]) for c in cols]
    for c in cols:
        SIGNAL[c] = out.loc[c].to_dict()
    return out


def show(cols, top=None):
    """Таблица сигнала группы, по убыванию лучшего подъема."""
    t = evaluate(cols)
    lifts = [f"подъем_{t_}" for t_ in MODEL_TARGETS]
    t = t.assign(лучший=t[lifts].max(axis=1)).sort_values("лучший", ascending=False).drop(columns="лучший")
    display((t.head(top) if top else t).style.format("{:.2f}").format("{:.1%}", subset=["доля_пропусков"])
            .background_gradient(cmap="Blues", subset=lifts, vmin=1, vmax=10))
    return t


