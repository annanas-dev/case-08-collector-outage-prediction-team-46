# оценки. Это известные периоды сбоев (переход на новую СМВУ с 2021-04-21, сбой июля 2021, обрыв апреля 2024,
# отсутствие данных 2026-06-01), две маски связи объекта, которые решаются только по записям строго до `D 00:00`,
# то есть так же, как их увидел бы сервис в полночь, и маска плановых работ:
#
# - «объект не подключен» – у объекта до суток `D` еще не было ни одной записи;
# - «объект не на связи» – объект обычно пишет постоянно (медиана больше 200 записей в сутки за 30 суток), но все
#   сутки `D − 1` молчал;
# - «плановые работы АКМ» – сутки окна планово-предупредительных работ (ППР) аппаратуры контроля метана с запасом
#   ±3 суток. Раз в год датчики метана объекта снимают на поверку, возвращают и сдают, проверяя тестовым газом, и
#   журнал в эти дни показывает «Обнаружен газ» сразу на большинстве газовых каналов объекта, а также отказы и
#   переключения оборудования при приемке. Это обслуживание, а не инциденты. Окна 2026 года взяты из графика ППР
#   заказчика, окна прошлых лет восстановлены по журналу: кластеры дней, когда тестовый газ виден на половине
#   газовых каналов объекта в рабочее время. Таблица окон лежит в `datasets/processed/maintenance/ppr_windows.parquet`.
#
# Тихие сутки подключенного объекта, который пишет редко (например, только дискретные датчики), не маскируются: для
# него отсутствие записей – обычный день без событий, то есть отрицательный пример. `выборка` делит время: обучение
# 2019-2024, валидация 2025, тест январь-июнь 2026.
