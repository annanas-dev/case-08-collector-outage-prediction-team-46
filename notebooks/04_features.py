# %% [markdown]
# ## 2. История объекта по классам инцидентов
#
# **Почему группа может работать.** Раздел 1 показал, что цель «помнит» свое прошлое на объекте. Если к тому же
# проблемные объекты остаются проблемными из года в год, то история объекта – это не только краткая память о
# вчерашнем сбое, но и долгая «репутация» объекта.
#
# ### 2.1 Устойчивы ли проблемные объекты
# **Проверка.** Для каждого объекта и года считаем долю суток с целью (только сутки без масок, объект должен
# иметь не меньше 100 рабочих суток в году) и ранговую корреляцию Спирмена этих долей между соседними годами
# обучающего периода. Корреляция около 1 – объекты сохраняют свой ранг риска, около 0 – каждый год проблемные
# объекты новые.

# %%
def yearly_share(t):
    d = grid.loc[OK, ["ид_объект", "день", f"цель_{t}"]]
    g = d.assign(год=d["день"].dt.year).groupby(["ид_объект", "год"])[f"цель_{t}"].agg(["mean", "size"])
    return g["mean"].where(g["size"] >= 100).unstack("год")


def spearman(a, b):
    """Ранговая корреляция по общим непропущенным значениям."""
    m = a.notna() & b.notna()
    return a[m].rank().corr(b[m].rank())


stab = {}
for t in MODEL_TARGETS:
    s = yearly_share(t)
    stab[t] = {f"{y}→{y + 1}": spearman(s[y], s[y + 1]) for y in range(2019, 2024)}
stab = pd.DataFrame(stab).T
s = yearly_share("отказ")
stab["объектов_в_паре_(мин)"] = min(int((s[y].notna() & s[y + 1].notna()).sum()) for y in range(2019, 2024))
display(stab.round(2))

