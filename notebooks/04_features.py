# ## 1. Горизонт памяти: какие окна брать
#
# **Наблюдение, с которого начинаем.** Инциденты на объекте не независимы: неисправный датчик сбоит днями,
# а сырой коллектор топит каждую весну. Если так, то «было ли это на объекте недавно» – главный кандидат в признаки.
# Но «недавно» – это сколько: вчера, неделю, месяц, квартал?
#
# **Проверка.** Для каждой цели и каждого сдвига `k` от 1 до 120 суток считаем, во сколько раз вероятность цели
# в сутки `D` выше, если та же цель была на объекте в сутки `D − k`: `P(y_D = 1 | y_{D−k} = 1) / P(y_D = 1)`.
# Берем только обучающий период и пары суток, где обе без маски. Где этот подъем затухает, там и кончается
# полезная память; окна признаков выбираем по форме кривой.

# %%
def lag_lift(t, lags):
    y = grid.pivot(index="день", columns="ид_объект", values=f"цель_{t}").astype(float)
    ok = grid.assign(ok=OK & (SPLIT == "обучение")).pivot(index="день", columns="ид_объект", values="ok")
    y = y.where(ok.astype(bool)).to_numpy()
    base = np.nanmean(y)
    out = {}
    for k in lags:
        a, b = y[k:], y[:-k]
        sel = (b == 1) & ~np.isnan(a)
        out[k] = np.nanmean(a[sel]) / base
    return pd.Series(out)


