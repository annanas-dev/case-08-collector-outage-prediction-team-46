# остальное сворачивается в «прочие», каналы вне справочника – отдельный цвет
FOCUS = list(dict.fromkeys([*_tot["количество_событий"].nlargest(3).index,
                            *_tot["количество_тревожных"].sort_values(ascending=False).index]))[:7]
TYPE_COLOR = {t: PALETTE[i] for i, t in enumerate(FOCUS)} | {UNKNOWN: PALETTE[7], OTHER: GREY}


def fold_types(wide: pd.DataFrame) -> pd.DataFrame:
    """Колонки-типы → фокусные типы + «прочие» + «нет в справочнике» (порядок фиксирован)."""
    keep = [t for t in FOCUS if t in wide.columns]
    rest = [c for c in wide.columns if c not in keep and c != UNKNOWN]
    out = wide[keep].copy()
    out[OTHER] = wide[rest].sum(axis=1)
    if UNKNOWN in wide.columns:
        out[UNKNOWN] = wide[UNKNOWN]
    return out.loc[:, out.sum() > 0]


def plot_lines(ax, wide: pd.DataFrame, **kw):
    for c in wide.columns:
        ax.plot(wide.index, wide[c], color=TYPE_COLOR.get(c), label=c, **kw)


