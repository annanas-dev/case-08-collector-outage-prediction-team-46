def profile(df, by):
    t = df.groupby(["тип_датчика", by])["количество_тревожных"].sum().unstack(fill_value=0)
    return t.div(t.sum(axis=1), axis=0)


def heatmap(ax, df, title, fmt="{:.1%}"):
    im = ax.imshow(df.values, aspect="auto", cmap="Blues", interpolation="nearest")
    ax.set_xticks(range(df.shape[1]), df.columns)
    ax.set_yticks(range(df.shape[0]), df.index)
    ax.grid(False)
    vmin, vmax = np.nanmin(df.values), np.nanmax(df.values)
    for i in range(df.shape[0]):
        for j in range(df.shape[1]):
            v = df.values[i, j]
            dark = (v - vmin) / max(vmax - vmin, 1e-12) > 0.6
            ax.text(j, i, fmt.format(v), ha="center", va="center", fontsize=7, color="white" if dark else INK)
    ax.set_title(title)
    return im


def profile_med(df, by):
    """Медиана годовых профилей: профиль каждого года, медиана по годам, нормировка на 1."""
    t = df.groupby(["тип_датчика", "год", by])["количество_тревожных"].sum().unstack(fill_value=0)
    t = t.div(t.sum(axis=1).replace(0, np.nan), axis=0).groupby(level="тип_датчика").median()
    return t.div(t.sum(axis=1), axis=0)


