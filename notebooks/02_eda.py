def with_channel_attrs(df: pd.DataFrame, cols=("тип_датчика", "ид_объект")) -> pd.DataFrame:
    """Left join со справочником: каналы вне справочника остаются, тип = UNKNOWN, объект = -1."""
    out = df.merge(channels_pd[["ид_канала_данных", *cols]], on="ид_канала_данных", how="left")
    if "тип_датчика" in cols:
        out["тип_датчика"] = out["тип_датчика"].fillna(UNKNOWN)
    if "ид_объект" in cols:
        out["ид_объект"] = out["ид_объект"].fillna(-1).astype("int32")
    return out


