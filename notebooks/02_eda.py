# ### 2.3 Повторяющиеся названия на одном объекте
# В справочнике на одном объекте встречаются каналы с одинаковым названием. Возможных объяснений четыре, и они
# дают разные следы в данных:
# - **замена оборудования** – старый канал перестает писать, новый с тем же названием начинает: группы будут
#   «последовательными»;
# - **несколько каналов одного устройства** (например, состояние и управление) – каналы живут параллельно
#   и имеют разные типы;
# - **смена классификации** – последовательные группы с разными типами;
# - **несколько одинаковых датчиков в одной точке** – параллельные однотипные группы.
#
# Группа – каналы справочника с одинаковыми (объект, название), которые хоть раз писали. Ограничение: у каналов вне
# справочника нет названия и объекта, поэтому замену «канал вне справочника → канал справочника» здесь не увидеть.

# %%
def chain_stats(g: pd.DataFrame) -> pd.Series:
    g = g.sort_values(["первый_день", "последний_день"])
    prev_last = g["последний_день"].cummax().shift()
    seq = bool((g["первый_день"] > prev_last).iloc[1:].all())
    return pd.Series({
        "число_каналов": len(g), "последовательная": seq,
        "день_смены": g["первый_день"].iloc[1] if seq else pd.NaT,
        "разрыв_сут": (g["первый_день"].iloc[1] - g["последний_день"].iloc[0]).days if seq else np.nan,
        "типы": tuple(sorted(g["тип_датчика"].unique())),
        # пересечение жизни всех каналов группы (сут; < 0 – есть разрыв) и «все начали в один день»
        "пересечение_сут": (g["последний_день"].min() - g["первый_день"].max()).days + 1,
        "общий_старт": g["первый_день"].nunique() == 1,
    })


