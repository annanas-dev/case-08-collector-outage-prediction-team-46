def to_episodes(df, gap_min=5):
    df = df.sort_values(["ид_объект", "минута"])
    new = (df["ид_объект"] != df["ид_объект"].shift()) | (df["минута"].diff() > pd.Timedelta(minutes=gap_min))
    ep_b = df.assign(эпизод=new.cumsum()).groupby("эпизод").agg(
        ид_объект=("ид_объект", "first"), начало=("минута", "min"), конец=("минута", "max"),
        пик=("каналов", "max"), медиана_длительности_с=("медиана_длительности_с", "max"))
    ep_b["длительность_мин"] = ((ep_b["конец"] - ep_b["начало"]).dt.total_seconds() / 60
                                + ep_b["медиана_длительности_с"] / 60)
    return ep_b


