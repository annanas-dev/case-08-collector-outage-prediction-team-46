def zone_breakdown(zone):
    """Окно сравнения той же длины против зоны: активных каналов в сутки (среднее) и событий в сутки по типам."""
    s, e, rs, re_ = zone_windows(zone)
    days = (e - s).days

    def f(x):
        return pd.DataFrame({"каналов": x[x["активен"]].groupby(["тип_датчика", "день"])["ид_канала_данных"].nunique()
                                         .groupby(level=0).sum() / days,
                             "событий_в_сутки": x.groupby("тип_датчика")["количество_событий"].sum() / days})

    out = f(window(daily_ch, rs, re_)).join(f(window(daily_ch, s, e)), how="outer",
                                            lsuffix="_до", rsuffix="_в_зоне").fillna(0)
    out["отношение_событий"] = out["событий_в_сутки_в_зоне"] / out["событий_в_сутки_до"].replace(0, np.nan)
    return out.sort_values("событий_в_сутки_до", ascending=False).round(2)


