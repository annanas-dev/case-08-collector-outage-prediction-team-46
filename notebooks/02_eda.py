# - **«Работают все насосы в АНС» – режим откачки, а не отказ**: за ним следует «Выключен» или «Включен»,
#   и эпизод короткий. Логичнее считать его предвестником подтопления.
# - **«Отключено устройство» и температурные состояния дают почти все длинные и «неснятые» тревоги**:
#   «Состояние УИР-Р / Отключено устройство» – 24,8 % эпизодов дольше 24 ч и 14,8 % открытых, «Ручной извещатель /
#   Отключено устройство» – 45,7 % дольше 24 ч, температура «Не определено» и «ниже 3ºC» – 12,8 и 13,0 %.
#   «Датчик дыма / Отключено устройство» – 8,2 %. Похоже на вывод оборудования из работы, а не на отказ.
#
# «Батарея неисправна» ни разу не была тревожной (2 691 запись у ИБП), «Неопределен» тоже не тревожен по флагу,
# его разберем как потерю связи в разделе 7.
#
# Сведем состояния в кандидаты классов инцидентов и посчитаем, сколько недребезговых эпизодов (≥ 60 с) дает каждый
# класс. Класс эпизода определяем двумя способами: по первому состоянию и по приоритету состояний в цепочке
# (подтопление > пожар > отказ > проникновение), чтобы подтопление не терялось внутри цепочек. Считаем только
# каналы справочника: для остальных нет объекта, и метку для них не построить.

# %%
A_STATES = {"Неисправен", "Обесточен", "Питание от батарей", "Батарея разряжена", "Много неисправных устройств"}
E_TYPES = {"КД АВ", "КД Дверь", "КД Люк", "Стекло", "9-секционный люк"}
PRIORITY = {"C. подтопление": 0, "D. пожар": 1, "A. отказ": 2, "E. проникновение": 3, "газ": 4,
            "температурный режим": 5, "откачка (АНС)": 6, "вывод из работы": 7, "прочее": 8}


def state_class(state: pd.Series, tp: pd.Series) -> pd.Series:
    """Кандидат в класс инцидента по паре (состояние, тип датчика)."""
    nz = state.eq("Не замкнут")
    conds = [
        state.eq("Затоплен") | (nz & tp.eq("Датчик затопления")),
        state.isin(["Обнаружен дым", "Рычаг сдернут"]) | (nz & tp.isin(["Тепловой датчик", "Ручной извещатель"])),
        state.isin(A_STATES) | (state.eq("Не определено") & tp.eq("Датчик температуры")),
        state.eq("Обнаружено движение") | (nz & tp.isin(E_TYPES)),
        state.eq("Обнаружен газ"),
        state.str.startswith("Температура", na=False),
        state.eq("Работают все насосы в АНС"),
        state.eq("Отключено устройство"),
    ]
    return pd.Series(np.select(conds, list(PRIORITY)[:-1], "прочее"), index=state.index)


