def objects_lost(zone, drop=0.5, min_channels=5, burst_days=2):
    """(объект, тип), у которых среднее число активных каналов в сутки в зоне упало больше чем на `drop` против окна
    сравнения той же длины. Для каждого – пачки «Неопределен» в ±burst_days от начала и конца зоны."""
    s, e, rs, re_ = zone_windows(zone)
    days = (e - s).days

    def active_per_day(df):
        df = df[(df["ид_объект"] >= 0) & df["активен"]]
        return df.groupby(["ид_объект", "тип_датчика", "день"])["ид_канала_данных"].nunique() \
            .groupby(level=["ид_объект", "тип_датчика"]).sum() / days

    res = pd.DataFrame({"активных_до": active_per_day(window(daily_ch, rs, re_)),
                        "активных_в_зоне": active_per_day(window(daily_ch, s, e))}).fillna(0)
    res = res[res["активных_до"] >= min_channels]
    res["падение"] = 1 - res["активных_в_зоне"] / res["активных_до"]
    lost = res[res["падение"] > drop].reset_index()

    pad = pd.Timedelta(days=burst_days)
    near = bursts[bursts["минута"].between(s - pad, s + pad) | bursts["минута"].between(e - pad, e + pad)]
    b = near.groupby("ид_объект").agg(пачек_у_границ=("каналов_в_неопределен", "size"),
                                      макс_каналов_в_неопределен=("каналов_в_неопределен", "max"))
    lost = lost.join(b, on="ид_объект").fillna({"пачек_у_границ": 0, "макс_каналов_в_неопределен": 0})
    lost.insert(1, "объект", lost["ид_объект"].map(obj_names))
    return lost.sort_values("падение", ascending=False).round(2)


for name, z in ZONES.items():
    print(name)
    display(objects_lost(z))

