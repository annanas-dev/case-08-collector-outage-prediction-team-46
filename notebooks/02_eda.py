# ### 0.2 Витрины
# Витрины строятся один раз (десятки минут) и дальше читаются из `datasets/processed/eda/`. Кроме общих витрин
# из `annanas.aggregates` здесь определены три своих:
# - `unknown_channels` – что пишут каналы, которых нет в справочнике (по часам, классу записи и состоянию);
# - `undefined_daily` – сколько записей «Неопределен» канал дал за сутки: канал, который за день записал только
#   «Неопределен», мы не будем считать активным;
# - `alarm_episodes` – эпизоды тревоги: подряд идущие тревожные записи канала до первой нетревожной
#   (подробно в разделе 5).
#
# Витрины читаются через Spark (`toPandas()` в сессии с московским временем), поэтому все метки времени московские.

# %%
def unknown_channels_profile():
    """События каналов, которых нет в справочнике: по часам, классу записи, состоянию и флагу тревожности."""
    return (events.join(F.broadcast(channels.select("ид_канала_данных")), "ид_канала_данных", "left_anti")
            .groupBy(F.date_trunc("hour", "дата_время").alias("час"), "класс_записи", "состояние", "тревожное")
            .agg(F.count("*").alias("количество_событий")))


def undefined_daily():
    """Число записей «Неопределен» канала за сутки."""
    return (events.filter(F.col("состояние") == "Неопределен")
            .groupBy(F.to_date("дата_время").alias("день"), "ид_канала_данных")
            .agg(F.count("*").alias("количество_неопределен")))


def alarm_episodes():
    """Эпизоды тревоги: подряд идущие тревожные записи канала (порядок дата_время, ид_события) до первой
    нетревожной. Конец эпизода – время первой нетревожной записи; если ее нет, эпизод открыт.
    В витрине state_runs `секунд_до_следующего` – время до следующей записи любого вида, поэтому
    длительность тревоги по ней занижена: здесь она считается по эпизоду."""
    w = Window.partitionBy("ид_канала_данных").orderBy("дата_время", "ид_события")
    prev = F.lag("тревожное").over(w)
    r = (V["state_runs"]
         .withColumn("предыдущее_тревожное", prev)
         .filter(F.col("тревожное"))
         .withColumn("начало_эпизода",
                     (F.col("предыдущее_тревожное").isNull() | ~F.col("предыдущее_тревожное")).cast("int"))
         .withColumn("номер_эпизода", F.sum("начало_эпизода").over(w.rowsBetween(Window.unboundedPreceding, 0))))
    return (r.groupBy("ид_канала_данных", "номер_эпизода")
            .agg(F.min("дата_время").alias("начало"), F.max("время_следующего").alias("время_после_последней"),
                 F.max(F.col("время_следующего").isNull().cast("int")).alias("открыт"),
                 F.count("*").alias("записей"),
                 F.min(F.struct("дата_время", "ид_события", "состояние"))["состояние"].alias("первое_состояние"),
                 F.max(F.struct("дата_время", "ид_события", "следующее_состояние"))["следующее_состояние"]
                 .alias("следующее_состояние"),
                 F.array_sort(F.collect_set("состояние")).alias("состояния"))
            .withColumn("конец", F.when(F.col("открыт") == 0, F.col("время_после_последней")))
            .drop("время_после_последней"))


